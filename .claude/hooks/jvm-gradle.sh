#!/bin/bash
# Run Gradle tasks against :core's JVM target only, for machines that cannot
# reach Google's Maven (dl.google.com) — Claude Code cloud sessions by default.
#
# Every project in the real build applies an AGP plugin, and AGP is published
# only to Google's Maven, so without that host Gradle cannot even configure the
# build. This generates a throwaway build beside it: core's own build script
# with the Android plugin and `androidLibrary { }` stripped out, pointed at the
# real sources through symlinks. It is regenerated on every run, so edits to
# core/build.gradle.kts carry over; if one stops stripping cleanly, this fails
# at configuration rather than testing something else.
#
#   .claude/hooks/jvm-gradle.sh :core:jvmTest
#   .claude/hooks/jvm-gradle.sh :core:jvmTest --tests 'chat.hc.core.session.*'
#   .claude/hooks/jvm-gradle.sh :core:phantomTest :core:legacyTest   # need hc/
#
# Reports land in ~/.cache/hcultra-jvm/core/build/, not core/build/.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
SHADOW="${HCULTRA_JVM_BUILD:-$HOME/.cache/hcultra-jvm}"

mkdir -p "$SHADOW/core"
ln -sfn "$REPO/core/src" "$SHADOW/core/src"
ln -sfn "$REPO/probe" "$SHADOW/probe"
cp "$REPO/gradle.properties" "$SHADOW/gradle.properties"

cat > "$SHADOW/settings.gradle.kts" <<EOF
// Generated by .claude/hooks/jvm-gradle.sh; edits are overwritten.
pluginManagement { repositories { gradlePluginPortal(); mavenCentral() } }
dependencyResolutionManagement {
    repositories { mavenCentral() }
    versionCatalogs { create("libs") { from(files("$REPO/gradle/libs.versions.toml")) } }
}
rootProject.name = "hcultra"
include(":core")
EOF

python3 - "$REPO/core/build.gradle.kts" "$SHADOW/core/build.gradle.kts" <<'PY'
import re, sys
src = open(sys.argv[1]).read()
out = src.replace("    alias(libs.plugins.android.kmp.library)\n", "")
out = re.sub(r"\n    androidLibrary \{.*?\n    \}\n", "\n", out, flags=re.S)
out = re.sub(r"        androidMain\.dependencies \{.*?\n        \}\n", "", out, flags=re.S)
if re.search(r"android(Library|Main)|android\.kmp", out):
    sys.exit("jvm-gradle.sh: core/build.gradle.kts changed shape; update the stripping in this script")
open(sys.argv[2], "w").write("// Generated by .claude/hooks/jvm-gradle.sh from core/build.gradle.kts.\n" + out)
PY

exec "$REPO/gradlew" -p "$SHADOW" "$@"
